from random import *

n = int(input("Введите количество элементов массива: "))

# Создаём список из слуйчайных чисел
a = []
for i in range(n):
    a.append(round(uniform(1, 100), 2))

# Располагаем числа по убыванию по заданию
a.sort(reverse=True)

print("Массив:", a)


y = float(input("Введите число y между первым и последним элементами: "))

# Проверяем, что y находится между числами массива
if y >= a[0] or y <= a[n - 1]:
    print("Число y должно быть меньше первого и больше последнего элемента.")
else:
    k = -1

    # Ищем число a[k], после которого находится y
    for i in range(n - 1):
        if a[i] > y and y > a[i + 1]:
            k = i
            break

    if k == -1:
        print("Не удалось найти подходящие соседние элементы.")
    else:
        print("k =", k + 1)
        print("a[k] =", a[k])

        # Берём числа, расположенные после a[k]
        after = a[k + 1:]

        # Находим их сумму
        total = sum(after)

        # Сортируем их по убыванию
        after.sort(reverse=True)

        print("Сумма элементов после a[k]:", total)
        print("Элементы после a[k] по убыванию:", after)
