def vvod(n):
    # Создаём пустой список для всей матрицы
    a = []

    
    for i in range(2 * n):
        # Просим ввести строку и превращаем введённые числа в список целых чисел
        stroka = list(map(int, input("Введите строку матрицы: ").split()))

        # Проверяем, что в строке ровно 2*n чисел
        while len(stroka) != 2 * n:
            print("Нужно ввести", 2 * n, "числа")
            stroka = list(map(int, input("Введите строку матрицы: ").split()))

        
        a.append(stroka)

    # Возвращаем заполненную матрицу
    return a


def pechat(a):
    
    for stroka in a:
        
        print(stroka)


def perestanovka(a, n):
    # Создаём копию исходной матрицы
    b = [stroka[:] for stroka in a]

    # i и j обозначают положение элемента внутри блока размером n на n
    for i in range(n):
        for j in range(n):
            # Верхний левый блок заменяем нижним правым
            b[i][j] = a[i + n][j + n]

            # Верхний правый блок заменяем нижним левым
            b[i][j + n] = a[i + n][j]

            # Нижний левый блок заменяем верхним правым
            b[i + n][j] = a[i][j + n]

            # Нижний правый блок заменяем верхним левым
            b[i + n][j + n] = a[i][j]

    # Возвращаем матрицу с переставленными блоками
    return b


def proizv_blokov(a, n):
    # x выбирает начальную строку блока: 0 или n
    for x in range(0, 2 * n, n):

        # y выбирает начальный столбец блока: 0 или n
        for y in range(0, 2 * n, n):
            
            p = 1

            # Перебираем строки выбранного блока
            for i in range(x, x + n):

                # Перебираем столбцы выбранного блока
                for j in range(y, y + n):
                    # Умножаем произведение на текущий элемент
                    p *= a[i][j]

            # Выводим произведение элементов этого блока
            print("Произведение блока:", p)



n = int(input("Введите n: "))


a = vvod(n)


print("Исходная матрица:")
pechat(a)


b = perestanovka(a, n)


print("Новая матрица:")
pechat(b)

# Поиск произведения четырёх блоков исходной матрицы
print("Произведения блоков исходной матрицы:")
proizv_blokov(a, n)

# Поиск произведения четырёх блоков новой матрицы
print("Произведения блоков новой матрицы:")
proizv_blokov(b, n)
